#!/usr/bin/env node
/**
 * Picks the ONE metro cost page per city that is submitted to search engines,
 * and writes src/content/metro-primary-guide.generated.ts.
 *
 *   node scripts/build-metro-primary-guide.mjs          # regenerate
 *   node scripts/build-metro-primary-guide.mjs --check  # fail if stale
 *
 * Why one per city: a city's verified local block (authority, code edition,
 * permit policy, registration, inspection items) is shared by every guide
 * page for that city. Measured on production on 2026-11-14, two guide pages
 * for the same city were 72-76% identical word for word, and the 401 indexed
 * metro pages were 59% of the sitemap while earning about 6% of search
 * clicks. Google AdSense declined the site for "Low value content" the same
 * day. Indexing one page per city keeps every piece of sourced local research
 * in the index once, instead of up to five times.
 *
 * Selection rule, per city, among guides that carry a verified byGuide fact:
 *   1. the guide whose metro page had the most Search Console impressions in
 *      the period recorded in research/search-console/ (so the page Google
 *      already shows for that city is the one that stays);
 *   2. otherwise the first guide in FALLBACK_ORDER, which is ordered by total
 *      metro-page impressions per guide in that same file.
 *
 * The other guide pages for the city stay live for readers and internal
 * links, with robots noindex,follow, and are left out of the sitemap.
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "src/content/metro-primary-guide.generated.ts");
const SC_DIR = join(root, "research/search-console");

const FALLBACK_ORDER = [
  "electrician-service-call",
  "garbage-disposal-replacement",
  "plumber-service-call",
  "smoke-detector-replacement",
  "water-heater-replacement",
];

// Newest impressions snapshot wins; file names sort by their ISO date.
const scFile = readdirSync(SC_DIR)
  .filter((f) => /^metro-impressions-\d{4}-\d{2}-\d{2}\.json$/.test(f))
  .sort()
  .pop();
if (!scFile) throw new Error("No metro-impressions-*.json under research/search-console");
const sc = JSON.parse(readFileSync(join(SC_DIR, scFile), "utf8"));

const { LOCAL_DETAIL } = await import(
  join(root, "src/content/local-detail.generated.ts")
);

const picks = {};
for (const city of Object.keys(LOCAL_DETAIL).sort()) {
  const guides = Object.keys(LOCAL_DETAIL[city].byGuide);
  if (guides.length === 0) continue;
  let best = null;
  let bestImpr = 0;
  for (const g of FALLBACK_ORDER) {
    if (!guides.includes(g)) continue;
    const impr = sc.impressions[`${g}/${city}`] ?? 0;
    if (impr > bestImpr) {
      best = g;
      bestImpr = impr;
    }
  }
  if (!best) best = FALLBACK_ORDER.find((g) => guides.includes(g)) ?? guides.sort()[0];
  picks[city] = best;
}

const body = `/**
 * GENERATED by scripts/build-metro-primary-guide.mjs -- do not hand-edit.
 *
 * The one metro cost guide per city that is indexable. Chosen from
 * research/search-console/${scFile} (${sc.period}).
 * See the script header for the rule and the reason.
 */
export const METRO_PRIMARY_GUIDE: Record<string, string> = ${JSON.stringify(picks, null, 2)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {}
  if (current !== body) {
    console.error("metro-primary-guide.generated.ts is stale. Run: node scripts/build-metro-primary-guide.mjs");
    process.exit(1);
  }
  console.log(`metro-primary-guide: up to date (${Object.keys(picks).length} cities)`);
} else {
  writeFileSync(OUT, body);
  const tally = {};
  for (const g of Object.values(picks)) tally[g] = (tally[g] ?? 0) + 1;
  console.log(`Wrote ${Object.keys(picks).length} cities`, tally);
}
