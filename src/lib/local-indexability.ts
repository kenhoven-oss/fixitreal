/**
 * Whether a programmatic metro page carries enough verified local data to be
 * submitted to search engines.
 *
 * Lives in lib/ with RELATIVE imports on purpose: the Node test runner used
 * by `npm run test:unit` does not resolve the `@/` path alias, and this rule
 * is the one piece of the metro layer that must be covered by tests. See
 * tests/local-indexability.test.ts. Keep this module free of `@/` imports.
 */
import { LOCAL_DETAIL } from "../content/local-detail.generated.ts";
import type { LocalDetail } from "../content/local-detail-types.ts";
import { METRO_PRIMARY_GUIDE } from "../content/metro-primary-guide.generated.ts";

/**
 * Verified local permit / code facts for a metro, or undefined when that
 * metro has not been researched.
 *
 * The data is generated by scripts/build-local-detail.mjs from the JSON under
 * research/local/ and must never be hand-edited.
 */
export function getLocalDetail(citySlug: string): LocalDetail | undefined {
  return LOCAL_DETAIL[citySlug];
}

/**
 * Deliberately per-guide, not per-city: a city having a published
 * water-heater permit fee says nothing about whether anything has been
 * verified on smoke detectors, so only pages with a byGuide entry go live.
 *
 * This cannot drift from what readers see — the predicate reads the same data
 * the page renders, so a page is indexable if and only if it carries the
 * content that justifies indexing it.
 *
 * And one page per city, not one per verified guide. A city's local block
 * (authority, code edition, permit policy, registration, inspection items) is
 * the same on every guide page for that city, so indexing all of them put the
 * same research in the index up to five times: two guide pages for one city
 * measured 72-76% identical on production (2026-11-14), the day AdSense
 * declined the site for "Low value content". METRO_PRIMARY_GUIDE names the
 * single guide that stays indexable for each city; it is generated by
 * scripts/build-metro-primary-guide.mjs, which documents how it is chosen.
 * The sibling pages stay live, noindex,follow, and out of the sitemap.
 */
export function isCityGuideIndexable(citySlug: string, guideSlug: string): boolean {
  const detail = LOCAL_DETAIL[citySlug];
  if (!detail) return false;
  if (!detail.byGuide[guideSlug]) return false;
  return METRO_PRIMARY_GUIDE[citySlug] === guideSlug;
}
